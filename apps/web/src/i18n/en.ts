const lower = (s: string) => s.charAt(0).toLowerCase() + s.slice(1);
const plural = (n: number, one: string, many = `${one}s`) => `${n} ${n === 1 ? one : many}`;
/** a day said inside a sentence: "tomorrow", "on Oct 3" */
const onDay = (day: string) => (day === 'Tomorrow' ? 'tomorrow' : `on ${day}`);
/** the two digits a five-day market's label names ("2·7일" → 2 and 7; 10 is said as 0) */
const marketDigits = (label: string) => (label.match(/\d+/g) ?? []).map((d) => String(Number(d) % 10));

